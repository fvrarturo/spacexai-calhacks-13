"""Write docs/BIGDATA_RESULTS.md from the big-data result files.

Every number in the generated report is copied from data/results/bigdata/*.json,
so the written summary cannot drift from the analyses. Run after any analysis:

    python3 -m analysis.bigdata_report
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'data/results/bigdata'
OUT = ROOT / 'docs/BIGDATA_RESULTS.md'
TABS = [('materials', '01 · Materials'), ('foundry', '02 · Foundry'), ('network', '03 · Network')]
GUIDANCE = ROOT / 'docs/appendix/PITCH_GUIDANCE.md'


def human_bytes(n):
    units = ['B', 'KB', 'MB', 'GB', 'TB', 'PB']
    v = float(n or 0); i = 0
    while v >= 1000 and i < len(units) - 1:
        v /= 1000; i += 1
    return f'{v:.1f} {units[i]}'


def listed(d):
    text = f"{d.get('name', '')} {d.get('notes', '')}".lower()
    return d.get('scope') == 'inventoried' or (not d.get('scope') and ('listobjects' in text or 'inventory' in text))


def main():
    results = []
    for path in sorted(RESULTS.glob('*.json')):
        if path.name == 'index.json':
            continue
        r = json.loads(path.read_text())
        if isinstance(r, dict) and 'id' in r and 'tab' in r:
            results.append(r)
    seen, jobs = {}, set()
    for r in results:
        for d in r.get('datasets', []):
            key = (d.get('url') or d.get('name') or '').lower() + '|' + str(d.get('scope'))
            seen.setdefault(key, (0 if listed(d) else int(d.get('bytes') or 0), 0 if listed(d) else int(d.get('records') or 0), int(d.get('bytes') or 0) if listed(d) else 0))
        jobs.update((r.get('compute') or {}).get('job_ids', []))
    processed = sum(v[0] for v in seen.values()); records = sum(v[1] for v in seen.values()); catalogued = sum(v[2] for v in seen.values())

    lines = ['# Big-data results — Orbital Foundry', '',
             'Generated by `python3 -m analysis.bigdata_report` from `data/results/bigdata/*.json`. Do not edit numbers here; re-run the analyses instead.', '',
             f'**{len(results)} analyses · {human_bytes(processed)} of public data processed · {records:,} records · {len(jobs)} Slurm jobs on MIT Engaging.** '
             f'In addition, {human_bytes(catalogued)} of NASA archive was catalogued object by object (listed, not downloaded).', '']
    for tab, title in TABS:
        group = [r for r in results if r['tab'] == tab]
        if not group:
            continue
        lines += [f'## {title}', '']
        for r in group:
            h = r.get('headline') or {}
            ds = r.get('datasets', [])
            size = human_bytes(sum(int(d.get('bytes') or 0) for d in ds if not listed(d)))
            lines += [f"### {r['title']}", '',
                      f"*{r.get('evidence_level', '')}* · {size} processed · methods: `docs/appendix/` · result file: `data/results/bigdata/{r['id']}.json`", '',
                      f"**{h.get('value', '')} {h.get('unit', '')}** — {h.get('text', '')}", '']
            if r.get('question'):
                lines += [f"Question: {r['question']}", '']
            if r.get('findings'):
                lines += ['Findings:'] + [f'- {f}' for f in r['findings']] + ['']
            if r.get('limitations'):
                lines += ['What it does not show:'] + [f'- {f}' for f in r['limitations']] + ['']
    if GUIDANCE.exists():
        lines += ['---', '', GUIDANCE.read_text().strip(), '']
    OUT.write_text('\n'.join(lines))
    print(f'Wrote {OUT.relative_to(ROOT)} ({len(results)} analyses)')


if __name__ == '__main__':
    main()
